const INTRO_KEY='rch-runs-cinematic-intro-session-v1';

function formatWhen(value:string){
 const date=new Date(value);
 if(!Number.isFinite(date.getTime()))return 'Time to be confirmed';
 return date.toLocaleString('en-US',{timeZone:'America/New_York',weekday:'short',month:'short',day:'numeric',hour:'numeric',minute:'2-digit'})+' ET';
}

/** A light, once-per-session title screen that leads straight into real Run play. */
export function RunsCinematicIntro({enabled,replayToken}:{enabled:boolean;replayToken:number}){
 const [step,setStep]=useState<'done'|'logo'|'world'>('done');
 const skipRef=useRef<HTMLButtonElement>(null);
 const enterRef=useRef<HTMLButtonElement>(null);
 const close=useCallback(()=>{
  setStep('done');
  try{window.sessionStorage.setItem(INTRO_KEY,'seen');}catch{/* Optional session storage. */}
 },[]);
 useEffect(()=>{
  if(!enabled)return;
  if(replayToken===0){
   try{if(window.sessionStorage.getItem(INTRO_KEY)==='seen')return;}catch{/* Continue without optional session storage. */}
  }
  if(window.matchMedia('(prefers-reduced-motion: reduce)').matches){
   setStep('world');
   return;
  }
  setStep('logo');
  const next=window.setTimeout(()=>setStep('world'),1450);
  const done=window.setTimeout(()=>{
   setStep('done');
   try{window.sessionStorage.setItem(INTRO_KEY,'seen');}catch{/* Optional. */}
  },2650);
  return()=>{window.clearTimeout(next);window.clearTimeout(done);};
 },[enabled,replayToken]);
 useEffect(()=>{
  if(!enabled||step==='done')return;
  const prevOverflow=document.body.style.overflow;
  const prevFocus=document.activeElement instanceof HTMLElement?document.activeElement:null;
  document.body.style.overflow='hidden';
  const keyboard=(event:KeyboardEvent)=>{
   if(event.key==='Escape'){event.preventDefault();close();}
   if(event.key==='Tab'){
    event.preventDefault();
    if(document.activeElement===enterRef.current)skipRef.current?.focus();else enterRef.current?.focus();
   }
  };
  document.addEventListener('keydown',keyboard);
  skipRef.current?.focus();
  return()=>{
   document.removeEventListener('keydown',keyboard);
   document.body.style.overflow=prevOverflow;
   prevFocus?.focus({preventScroll:true});
  };
 },[enabled,step,close]);
 if(!enabled||step==='done')return null;
 return <div className={'rch-intro-overlay stage-'+step} role="dialog" aria-modal="true" aria-label="Entering RCH Runs">
  <div className="rch-intro-court" aria-hidden="true"/>
  <div className="rch-intro-stage" aria-live="off">
   <span className="rch-intro-crown" aria-hidden="true"><FaCrown/></span>
   <p className="rch-intro-logo">RCH <em>RUNS</em></p>
   <div className="rch-intro-pulse" aria-hidden="true"><FaBasketball/></div>
   <strong>{step==='logo'?'THE REAL-WORLD BASKETBALL GAME':'YOUR CITY. YOUR RUNS.'}</strong>
   <span>{step==='logo'?'REAL COURTS · REAL HOOPERS':'PLAY IN REAL LIFE. BUILD YOUR RCH LEGACY.'}</span>
   {step==='world'&&<button ref={enterRef} type="button" className="rch-intro-enter" onClick={close}>ENTER RUNS <FaArrowRight aria-hidden="true"/></button>}
  </div>
  <button ref={skipRef} type="button" className="rch-intro-skip" onClick={close} aria-label="Skip cinematic opening">SKIP <FaXmark aria-hidden="true"/></button>
 </div>;
}

type PlayerOverview={repBalance:number|null;verifiedGames:number|null;badges:number|null};
type Props={
 city:string|null;
 signedIn:boolean;
 name:string;
 avatar:string|null;
 journey:WorldJourney|null;
 journeyLoading:boolean;
 player:PlayerOverview;
 runs:readonly WorldRun[];
 featuredRunIds:readonly string[];
 onWorld:()=>void;
 onMissions:()=>void;
 onPlayer:()=>void;
 onVault:()=>void;
 onBattle:()=>void;
 onRules:()=>void;
 onReplay:()=>void;
};

export function RunsCinematicHome({
 city,signedIn,name,avatar,journey,journeyLoading,player,runs,featuredRunIds,
 onWorld,onMissions,onPlayer,onVault,onBattle,onRules,onReplay
}:Props){
 const db=useMemo(()=>getSupabaseClient(true) as any,[]);
 const [selectedMode,setSelectedMode]=useState<'quick'|'verified'|'takeover'|'partners'>('quick');
 const [statewideRuns,setStatewideRuns]=useState<WorldRun[]>([]);
 const [verifiedRunIds,setVerifiedRunIds]=useState<Set<string>>(new Set());
 const [verifiedRunsLoading,setVerifiedRunsLoading]=useState(false);
 const [finding,setFinding]=useState(false);
 useEffect(()=>{
  // A public basketball court suggestion is not a committed, hosted game.
  // Look beyond the first few autogenerated circuit rows before selecting
  // the statewide home card; the server still owns registration/verification.
  if(city||!db){setStatewideRuns([]);return;}
  let active=true;
  setFinding(true);
  const load=async()=>{
   const {data,error}=await db.from('runs')
    .select('id,title,location,location_slug,starts_at,status,game_format,run_type')
    .eq('status','open').gte('starts_at',new Date().toISOString())
    .order('starts_at',{ascending:true}).limit(500);
   if(error)throw error;
   const candidates=(data||[]) as WorldRun[];
   const ids=candidates.map(run=>run.id);
   if(!ids.length){if(active)setStatewideRuns([]);return;}
   const {data:circuit,error:circuitError}=await db.from('rch_weekend_circuit_events')
    .select('run_id').in('run_id',ids);
   if(circuitError)throw circuitError;
   const suggested=new Set(((circuit||[]) as Array<{run_id:string}>).map(r=>r.run_id));
   if(active)setStatewideRuns(candidates.filter(run=>!suggested.has(run.id)));
  };
  void load().catch(()=>{if(active)setStatewideRuns([]);})
   .finally(()=>{if(active)setFinding(false);});
  return()=>{active=false;};
 },[db,city]);
 const candidateRuns=city?runs:statewideRuns;
 useEffect(()=>{
  const ids=candidateRuns.map(run=>run.id);
  if(!db||ids.length===0){setVerifiedRunIds(new Set());setVerifiedRunsLoading(false);return;}
  let active=true;
  setVerifiedRunsLoading(true);
  void db.from('rch_run_verifications').select('run_id').in('run_id',ids).eq('verification_status','verified')
   .then(({data,error}:{data:Array<{run_id:string}>|null;error:unknown})=>{
    if(active){setVerifiedRunIds(error?new Set():new Set((data||[]).map(row=>row.run_id)));setVerifiedRunsLoading(false);}
   }).catch(()=>{if(active){setVerifiedRunIds(new Set());setVerifiedRunsLoading(false);}});
  return()=>{active=false;};
 },[db,candidateRuns]);
 const nextRun=candidateRuns.find(run=>run.status==='open')||null;
 const verifiedRun=candidateRuns.find(run=>run.status==='open'&&verifiedRunIds.has(run.id))||null;
 const progress=journey?.signed_in?worldXpProgress(journey.world_xp):null;
 const displayLevel=progress?.level??null;
 const doubleRep=Boolean(nextRun&&featuredRunIds.includes(nextRun.id));
 const missions=weeklyQuestCatalog.slice(0,3);
 const nextHref=nextRun?'/runs/'+encodeURIComponent(nextRun.id):'/runs?view=list#rch-upcoming-runs';
 const modeBriefing={
  quick:{index:'01',label:'QUICK RUN',subtitle:'OPEN PLAY',icon:FaBasketball,objective:'Get on a real court.',description:'Choose an open hosted game and follow its lobby. No opponent is simulated. Competitive ratings and rewards require an eligible game and independent score review.',steps:['Choose an open Run','Claim your roster spot','Check in at the court','Play the real game'],action:nextRun?'ENTER RUN LOBBY':'FIND A REAL RUN',href:nextHref},
  verified:{index:'02',label:'RCH VERIFIED RUN',subtitle:'ORGANIZER-REVIEWED EVENT',icon:FaShieldHalved,objective:'Join an event reviewed by RCH.',description:'RCH reviews the organizer, court source and event readiness. This badge is separate from score verification: game results still need their own review.',steps:['Choose a verified event','Claim your roster spot','Check in with the host','Submit scores for review'],action:verifiedRun?'ENTER VERIFIED RUN':'FIND A VERIFIED RUN',href:verifiedRun?'/runs/'+encodeURIComponent(verifiedRun.id):'/runs?view=list&verified=1#rch-upcoming-runs'},
  takeover:{index:'03',label:'TERRITORY TAKEOVER',subtitle:'CREW COMPETITION',icon:FaCrown,objective:'Challenge for court control.',description:'Choose a court, then have a crew captain challenge its controller. The other crew must accept; only a verified crew game can change territory.',steps:['Choose a court','Request a crew challenge','Play after acceptance','Verify the result'],action:'SELECT A COURT',href:'/runs?view=world&mode=world'},
  partners:{index:'04',label:'PARTNER EVENTS',subtitle:'APPROVED ORGANIZERS',icon:FaPeopleGroup,objective:'Find an event run by a verified partner.',description:'Browse approved Virginia basketball organizations, their event schedules and results. Partner approval does not automatically verify a score; competitive rewards still require independent review.',steps:['Choose an organizer','Review the event details','Join its real roster','Play and post highlights'],action:'EXPLORE PARTNER EVENTS',href:'/runs/partners'}
 }[selectedMode];
 const ModeIcon=modeBriefing.icon;
 return <section className="rch-gh" aria-label="Runs Game Home">
  <header className="rch-gh-top">
   <div className="rch-gh-wordmark" aria-label="RCH Runs"><span>RCH</span> <em>RUNS</em><FaCrown aria-hidden="true"/></div>
   <div className="rch-gh-top-actions">
    <button type="button" className="rch-gh-guide" onClick={onRules}><FaBookOpen/> <span>How to play</span></button>
    <Link href="/notifications" aria-label="Open notifications" className="rch-gh-icon"><FaBell/></Link>
    <button type="button" onClick={onPlayer} className="rch-gh-avatar" aria-label="Open My Player">
     {avatar?<img src={avatar} alt=""/>:<FaCrown aria-hidden="true"/>}
    </button>
   </div>
  </header>

  <div className="rch-gh-cinema">
   <span className="rch-gh-live"><span aria-hidden="true"/> {city?city.toUpperCase()+' COURTS':'VIRGINIA BASKETBALL'}</span>
   <div className="rch-gh-cinema-copy">
    <span className="rch-gh-eyebrow">RUNS 2.0 · THE REAL-WORLD BASKETBALL GAME</span>
    <h1>YOUR CITY.<br/><span>YOUR RUNS.</span></h1>
    <p>Find real courts. Meet real hoopers. Build a legacy you can prove.</p>
    <div className="rch-gh-entrance-actions">
     <a href="#rch-game-modes-title" className="rch-gh-find"><FaPlay aria-hidden="true"/> CHOOSE GAME MODE <FaArrowRight/></a>
     <button type="button" onClick={onWorld} className="rch-gh-explore"><FaCompass/> EXPLORE WORLD <FaArrowRight/></button>
    </div>
   </div>
   <div className="rch-gh-cinema-foot"><FaLocationDot/> REAL COURTS · REAL PEOPLE · REAL RUNS</div>
  </div>
  <section className="rch-gh-section rch-gh-mode-console rch-gh-arena-console" aria-labelledby="rch-game-modes-title">
   <div className="rch-gh-section-title"><h2 id="rch-game-modes-title">ENTER THE RUNS ARENA</h2><button type="button" onClick={onRules}>HOW TO PLAY <FaArrowRight/></button></div>
   <p className="rch-gh-game-start-copy">Pick your mission. Your game lobby will show the next move and keep your real game status clear.</p>
   <div className="rch-gh-mode-console-grid">
    <div className="rch-gh-mode-select" role="group" aria-label="Select a Runs game mode">
     {([
      ['quick','01','QUICK RUN','Open play',FaBasketball],
      ['verified','02','RCH VERIFIED RUN','Organizer reviewed',FaShieldHalved],
      ['takeover','03','TERRITORY TAKEOVER','Crew competition',FaCrown],
      ['partners','04','PARTNER EVENTS','Approved organizers',FaPeopleGroup]
     ] as const).map(([id,index,label,detail,Icon])=><button type="button" key={id} aria-pressed={selectedMode===id} onClick={()=>setSelectedMode(id)} className={'rch-gh-mode-option '+(selectedMode===id?'active':'')}>
       <span className="rch-gh-mode-option-index">{index}</span><Icon aria-hidden="true"/><span className="rch-gh-mode-option-copy"><strong>{label}</strong><small>{detail}</small></span><FaArrowRight className="rch-gh-mode-option-arrow" aria-hidden="true"/>
      </button>)}
     <div className="rch-gh-mode-select-foot"><FaShieldHalved aria-hidden="true"/><span>REAL PEOPLE · REAL RESULTS · SERVER-VERIFIED PROGRESS</span></div>
    </div>
    <article className={'rch-gh-mode-briefing mode-'+selectedMode} aria-live="polite" aria-labelledby="rch-mode-briefing-title">
     <div className="rch-gh-briefing-top"><span>MODE {modeBriefing.index} / 04</span><span><i aria-hidden="true"/> MODE SELECTED</span></div>
     <div className="rch-gh-briefing-heading"><span className="rch-gh-briefing-icon"><ModeIcon aria-hidden="true"/></span><div><small>{modeBriefing.subtitle}</small><h3 id="rch-mode-briefing-title">{modeBriefing.label}</h3></div></div>
     <p className="rch-gh-briefing-objective"><span>OBJECTIVE</span><strong>{modeBriefing.objective}</strong></p>
     <p className="rch-gh-briefing-description">{modeBriefing.description}</p>
     {selectedMode==='quick'&&nextRun&&<div className="rch-gh-mode-run-target"><span><FaBasketball aria-hidden="true"/> NEXT OPEN GAME</span><strong>{nextRun.title}</strong><small><FaLocationDot aria-hidden="true"/> {nextRun.location||'Court details in event'}</small><small><FaCalendarDays aria-hidden="true"/> {formatWhen(nextRun.starts_at)} · {nextRun.game_format||'Format to be confirmed'}</small></div>}
     {selectedMode==='verified'&&verifiedRun&&<div className="rch-gh-mode-run-target verified"><span><FaShieldHalved aria-hidden="true"/> RCH VERIFIED EVENT</span><strong>{verifiedRun.title}</strong><small><FaLocationDot aria-hidden="true"/> {verifiedRun.location||'Court details in event'}</small><small><FaCalendarDays aria-hidden="true"/> {formatWhen(verifiedRun.starts_at)} · {verifiedRun.game_format||'Format to be confirmed'}</small></div>}
     {selectedMode==='verified'&&!verifiedRun&&(verifiedRunsLoading?<p className="rch-gh-briefing-caveat" role="status">Checking upcoming RCH Verified Runs…</p>:<p className="rch-gh-briefing-caveat">No upcoming RCH Verified Run is listed in this area right now. The verified-event filter shows the currently available listings.</p>)}
     <div className="rch-gh-briefing-steps" aria-label="Mode steps">
      {modeBriefing.steps.map((step,index)=><div className="rch-gh-briefing-step" key={step}><span>{String(index+1).padStart(2,'0')}</span><strong>{step}</strong>{index<modeBriefing.steps.length-1&&<i aria-hidden="true"/>}</div>)}
     </div>
     {selectedMode==='takeover'?<button type="button" onClick={onWorld} className="rch-gh-mode-cta">{modeBriefing.action} <FaArrowRight aria-hidden="true"/></button>:<Link href={modeBriefing.href} className="rch-gh-mode-cta">{modeBriefing.action} <FaArrowRight aria-hidden="true"/></Link>}
     {selectedMode==='quick'&&<small className="rch-gh-briefing-caveat">The Run lobby guides roster, check-in, game-day, and result status.</small>}
     {selectedMode==='verified'&&<small className="rch-gh-briefing-caveat">Event verification covers organizer and readiness. It does not guarantee safety or certify the final score.</small>}
     {selectedMode==='takeover'&&<small className="rch-gh-briefing-caveat">A crew and captain are required. Select a real court, then open its Takeover challenge.</small>}
     {selectedMode==='partners'&&<small className="rch-gh-briefing-caveat">Partner approval confirms the organizer. Review each event’s venue, time, rules and fees before joining.</small>}
    </article>
   </div>
  </section>


  <div className="rch-gh-player-card">
   <button type="button" className="rch-gh-portrait" onClick={onPlayer} aria-label="Open My Player">
    {avatar?<img src={avatar} alt=""/>:<FaBasketball aria-hidden="true"/>}
   </button>
   <div className="rch-gh-player-main">
    <span className="rch-gh-kicker">{signedIn?'MY PLAYER · VERIFIED PROGRESSION':'YOUR BASKETBALL JOURNEY'}</span>
    <strong>{signedIn?name:'CREATE YOUR PLAYER'}</strong>
    <div className="rch-gh-level">
     <span>{displayLevel!==null?'HOOPER LVL '+displayLevel:journeyLoading?'SYNCING WORLD XP':'HOOPER LEVEL —'}</span>
     <small>{progress?progress.within.toLocaleString()+' / '+progress.toNext.toLocaleString()+' XP':'Earn XP from verified games'}</small>
    </div>
    <progress max={progress?.toNext||1} value={progress?.within||0} aria-label="World XP toward next level"/>
   </div>
   <button type="button" className="rch-gh-player-crown" onClick={onPlayer} aria-label="View player progression"><FaCrown/></button>
  </div>

  <div className="rch-gh-metrics" aria-label="Your verified performance">
   <div><FaShieldHalved/><strong>{player.verifiedGames===null?'—':player.verifiedGames}</strong><span>VERIFIED GAMES</span></div>
   <div><FaCrown/><strong>{player.repBalance===null?'—':player.repBalance.toLocaleString()}</strong><span>REP WALLET</span></div>
   <div><FaMedal/><strong>{player.badges===null?'—':player.badges}</strong><span>RUN BADGES</span></div>
  </div>

  <section className="rch-gh-section" aria-labelledby="rch-next-run">
   <div className="rch-gh-section-title"><h2 id="rch-next-run">YOUR NEXT PLAY</h2></div>
   {nextRun?<Link className="rch-gh-next-card" href={nextHref}>
    <span className="rch-gh-run-photo" aria-hidden="true"><FaBasketball/></span>
    <span className="rch-gh-run-body"><strong>{nextRun.title}</strong><small><FaLocationDot/> {nextRun.location||'Court details in event'}</small><small><FaCalendarDays/> {formatWhen(nextRun.starts_at)} · {nextRun.game_format}</small></span>
    {doubleRep&&<span className="rch-gh-double">2× VERIFIED REP</span>}
    <FaArrowRight className="rch-gh-run-arrow"/>
   </Link>:<div className="rch-gh-next-empty">{finding?'Checking real hosted games…':city?'No hosted Runs are scheduled here yet. Browse other Runs or host the first game.':'No hosted Runs are scheduled yet. Browse available games or host the first one.'}</div>}
   <div className="rch-gh-next-actions"><Link href="/runs?create=1" className="rch-gh-next-secondary">HOST A RUN</Link></div>
  </section>

  <section className="rch-gh-section" aria-labelledby="rch-quick-actions">
   <div className="rch-gh-section-title"><h2 id="rch-quick-actions">QUICK ACTIONS</h2></div>
   <div className="rch-gh-actions">
    <button type="button" onClick={onWorld}><FaCompass/><span>COURTS</span></button>
    <button type="button" onClick={onBattle}><FaBasketball/><span>COMPETE</span></button>
    <button type="button" onClick={onVault}><FaTrophy/><span>PROGRESS</span></button>
    <Link href="/crews?intent=mine"><FaPeopleGroup/><span>CREW</span></Link>
   </div>
  </section>

  <section className="rch-gh-section" aria-labelledby="rch-objectives">
   <div className="rch-gh-section-title"><h2 id="rch-objectives">YOUR MISSIONS</h2><button type="button" onClick={onMissions}>VIEW ALL <FaArrowRight/></button></div>
   <div className="rch-gh-mission-grid">{missions.map(m=>{
    const current=journey?.signed_in?Math.min(m.target,worldQuestProgress(journey,m.key)):0;
    return <button type="button" onClick={onMissions} key={m.key} className="rch-gh-mission">
     <span aria-hidden="true">{m.icon}</span><strong>{m.title}</strong>
     <small>{current}/{m.target}</small><progress max={m.target} value={current} aria-label={m.title+' progress'}/>
    </button>;
   })}</div>
   <p className="rch-gh-fair"><FaShieldHalved/> World XP comes from verified games and play at distinct courts. Scouting alone does not award REP or a competitive title.</p>
  </section>
  <div className="rch-gh-footer"><button type="button" onClick={onReplay}><FaPlay/> Replay entrance</button><span>REAL RUNS. REAL HOOPERS. RICH CITY.</span></div>
 </section>;
}
